class CustomsRule {
  final String countryName;
  final String currencyLimit;
  final List<String> allowedItems;
  final List<String> restrictedItems;
  final List<String> prohibitedItems;
  final String importantTip;

  CustomsRule({
    required this.countryName,
    required this.currencyLimit,
    required this.allowedItems,
    required this.restrictedItems,
    required this.prohibitedItems,
    required this.importantTip,
  });

  // قاعدة بيانات تجريبية محلية حسب كود الدولة/المطار أوفلاين
  static CustomsRule getDataForAirport(String airportCode) {
    // إذا كان المطار في السعودية (RUH, JED, etc.)
    if (['RUH', 'JED', 'DMM', 'MED', 'TIF'].contains(airportCode)) {
      return CustomsRule(
        countryName: 'المملكة العربية السعودية',
        currencyLimit: '60,000 ريال سعودي (أو ما يعادلها) قبل وجوب الإفصاح الجمركي.',
        allowedItems: [
          'الأمتعة الشخصية والهدايا بقيمة إجمالية لا تزيد عن 3,000 ريال.',
          'الكميات المعتادة من السجائر (حلقتين / 200 سيجارة) للاستخدام الشخصي.',
          'الأدوية الشخصية بكميات تكفي فترة الرحلة بشرط وجود وصفة طبية.',
        ],
        restrictedItems: [
          'الأجهزة الطبية والإلكترونية الحساسة (تتطلب تصاريح خاصة إذا كانت بكميات تجارية).',
          'المكملات الغذائية بكميات كبيرة.',
        ],
        prohibitedItems: [
          'المخدرات بأنواعها كافة والمؤثرات العقلية.',
          'اللحوم والأغذية الطازجة غير المصرحة أو القادمة من مناطق محظورة.',
          'الكتب أو المطبوعات المخالفة للتعاليم الإسلامية أو الأنظمة العامة.',
          'أجهزة التجسس وكاميرات الطائرات بدون طيار (الدرون) إلا بترخيص مسبق.',
        ],
        importantTip: 'يُمنع منعاً باتاً جلب المنتجات المصنوعة من حيوانات مهددة بالانقراض أو الأدوات الحادة غير المبررة.',
      );
    } 
    // إذا كان المطار في الإمارات (DXB, AUH, etc.)
    else if (['DXB', 'AUH', 'SHJ', 'RKT'].contains(airportCode)) {
      return CustomsRule(
        countryName: 'الإمارات العربية المتحدة',
        currencyLimit: '60,000 درهم إماراتي (أو ما يعادلها بالعملات الأجنبية) حد الإفصاح.',
        allowedItems: [
          'الهدايا الشخصية بقيمة لا تتجاوز 3,000 درهم.',
          '400 سيجارة أو ما يعادلها من التبغ.',
          'الأدوية الشخصية للاستخدام لمدة لا تتجاوز 3 أشهر مع وصفة طبية معتمدة.',
        ],
        restrictedItems: [
          'الأدوية النفسية والمخدرة (تتطلب تقريراً طبياً مصدقاً وطلب إلكتروني مسبق من وزارة الصحة).',
          'أجهزة الإرسال اللاسلكي.',
        ],
        prohibitedItems: [
          'اللحوم غير الحلال أو الأغذية المنزلية غير المكتوبة ببطاقات تعريفية واضحة.',
          'العملات المزيفة أو المواد الإباحية.',
          'أجهزة القمار والأدوات الممنوعة قانوناً.',
        ],
        importantTip: 'الأدوية المهدئة والمنومات تخضع لرقابة صارمة جداً، ويجب الإفصاح عنها فور وصولك لتجنب المساءلة.',
      );
    }
    // الافتراضي (مصر أو أي دولة أخرى مثل CAI, HBE, etc.)
    else {
      return CustomsRule(
        countryName: 'مصر',
        currencyLimit: '10,000 دولار أمريكي (أو ما يعادلها بالعملات الأخرى) الحد الأقصى للنقد المصحوب دون إفصاح.',
        allowedItems: [
          'الأمتعة الشخصية ذات الاستخدام الشخصي.',
          'الهواتف المحمولة والأجهزة اللوحية الشخصية المعتادة.',
          'مستحضرات التجميل والأدوية الشخصية بالكميات المعقولة.',
        ],
        restrictedItems: [
          'الدرونز (طائرات التصوير عن بعد) ممنوعة نهائياً إلا بتصريح أمني مسبق.',
          'الدروس الطبية والأجهزة الطبية المتقدمة.',
        ],
        prohibitedItems: [
          'المواد المخدرة والمهدئات غير المرخصة.',
          'الأسلحة والذخائر والألعاب النارية.',
          'الكتب والمطبوعات التي تتعارض مع الآداب العامة.',
        ],
        importantTip: 'تأكد من عدم جلب أجهزة لاسلكية أو طائرات بدون طيار لأنها تُحتجز في الجمرك فوراً وتتطلب إجراءات أمنية.',
      );
    }
  }
}